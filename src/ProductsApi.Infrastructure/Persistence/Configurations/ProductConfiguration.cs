using ProductsApi.Domain.Products;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace ProductsApi.Infrastructure.Persistence.Configurations;

/// <summary>
/// Mapeo de Product a la tabla public.products (creada por database/01_create_tables.sql).
/// El mapeo ORM vive en Infrastructure: el dominio queda 100% libre de atributos de EF.
/// Si se cambia algo aqui, actualizar tambien el script SQL (y viceversa).
/// </summary>
internal sealed class ProductConfiguration : IEntityTypeConfiguration<Product>
{
    public void Configure(EntityTypeBuilder<Product> builder)
    {
        builder.ToTable("products", "public", t =>
        {
            t.HasCheckConstraint("ck_products_price", "price >= 0");
            t.HasCheckConstraint("ck_products_stock", "stock >= 0");
        });

        builder.HasKey(p => p.Id).HasName("pk_products");
        builder.Property(p => p.Id)
            .HasColumnName("id")
            .UseIdentityByDefaultColumn(); // INTEGER GENERATED BY DEFAULT AS IDENTITY

        builder.Property(p => p.Name)
            .HasColumnName("name")
            .HasMaxLength(Product.NameMaxLength)
            .IsRequired();

        builder.Property(p => p.Description)
            .HasColumnName("description")
            .HasMaxLength(Product.DescriptionMaxLength);

        builder.Property(p => p.Price)
            .HasColumnName("price")
            .HasPrecision(18, 2)
            .IsRequired();

        builder.Property(p => p.Stock)
            .HasColumnName("stock")
            .IsRequired();

        // timestamptz: Npgsql exige DateTime con Kind = Utc (se obtiene de TimeProvider.GetUtcNow()).
        builder.Property(p => p.CreatedAt)
            .HasColumnName("created_at")
            .HasColumnType("timestamp with time zone")
            .IsRequired();

        builder.Property(p => p.UpdatedAt)
            .HasColumnName("updated_at")
            .HasColumnType("timestamp with time zone");
    }
}
